#!/usr/bin/env python3
"""Export the Oric game's data tables for the C64 port as ca65 source.

  python3 tools/export_tables.py

Writes c64/src/oric_tables.inc from oric/game_0400.bin (from `make oric`), each table under its disassembly label
(tools/symbols.py), so the port uses the original bytes rather than copies typed by hand.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import symbols  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME = open(os.path.join(ROOT, 'oric', 'game_0400.bin'), 'rb').read()
OUT = os.path.join(ROOT, 'c64', 'src', 'oric_tables.inc')

# label: number of bytes the C64 code uses
TABLES = {
    'ExplodeDX': 32,
    'ExplodeDY': 32,
    'BonusGfx': 24,
    'BonusFrameOfs': 5,
    'GlyphBike': 16,
}


def main():
    start = {name: a for a, _, _, name, _ in symbols.GAME_RANGES if name}
    lines = ['; Light Cycle (C64) — data tables copied from the Oric GAME block.',
             '; GENERATED by tools/export_tables.py from oric/game_0400.bin: do not edit.', '']
    for name, size in TABLES.items():
        a = start[name]
        data = GAME[a - 0x0400:a - 0x0400 + size]
        lines.append('%s:                     ; Oric $%04X' % (name, a))
        for i in range(0, size, 8):
            lines.append('        .byte   ' + ', '.join('$%02X' % b for b in data[i:i + 8]))
    open(OUT, 'w').write('\n'.join(lines) + '\n')
    print(os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
